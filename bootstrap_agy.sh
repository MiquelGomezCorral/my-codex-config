#!/usr/bin/env bash
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
CODEX_SOURCE="$ROOT/codex"
SKILLS_SOURCE="$ROOT/agent-home/skills"
AGY_CONFIG_ROOT="${AGY_CONFIG_ROOT:-$HOME/.gemini/config}"
AGY_PLUGIN_TARGET="$AGY_CONFIG_ROOT/plugins/my-codex-config"
AGY_GLOBAL_AGENTS="$AGY_CONFIG_ROOT/agents"
BACKUP_ROOT="${BACKUP_ROOT:-${XDG_STATE_HOME:-$HOME/.local/state}/my-codex-config/backups/$(date +%Y%m%d-%H%M%S)}"
RENDER_DIR=""

backup_existing() {
  local target=$1
  local relative_target backup_target backup_index=1

  relative_target=${target#"$HOME"/}
  [[ "$relative_target" != "$target" ]] || relative_target=".gemini/config/${target##*/}"
  backup_target="$BACKUP_ROOT/$relative_target"
  while [[ -e "$backup_target" || -L "$backup_target" ]]; do
    backup_target="$BACKUP_ROOT/$relative_target.$backup_index"
    ((backup_index += 1))
  done
  mkdir -p -m 700 "$(dirname "$backup_target")"
  chmod 700 "$BACKUP_ROOT"
  mv "$target" "$backup_target"
  printf 'Backed up %s to %s\n' "$target" "$backup_target"
}

ensure_directory() {
  local target=$1

  if [[ -e "$target" || -L "$target" ]] && [[ ! -d "$target" || -L "$target" ]]; then
    backup_existing "$target"
  fi
  mkdir -p "$target"
}

link_managed() {
  local source=$1
  local target=$2

  mkdir -p "$(dirname "$target")"
  if [[ -L "$target" && "$(readlink "$target")" == "$source" ]]; then
    return
  fi
  if [[ -e "$target" || -L "$target" ]]; then
    backup_existing "$target"
  fi
  ln -s "$source" "$target"
}

install_generated_file() {
  local source=$1
  local target=$2

  if [[ -f "$target" && ! -L "$target" ]] && cmp -s "$source" "$target"; then
    chmod 600 "$target"
    return
  fi
  if [[ -e "$target" || -L "$target" ]] && {
    [[ -L "$target" ]] || ! grep -q '^# Generated by my-codex-config bootstrap\.$' "$target" 2>/dev/null
  }; then
    backup_existing "$target"
  fi
  install -m 600 "$source" "$target"
}

render_agents() {
  local target=$1

  python3 - "$CODEX_SOURCE/agents" "$target" <<'PY'
import json
import pathlib
import sys
import tomllib

source = pathlib.Path(sys.argv[1])
target = pathlib.Path(sys.argv[2])
read_tools = ["view_file", "find_by_name", "grep_search", "list_dir", "run_command"]
write_tools = read_tools + ["replace_file_content"]

for path in sorted(source.glob("*.toml")):
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    name = data["name"]
    if name != path.stem:
        raise SystemExit(f"Agent name does not match filename: {path}")
    prompt = data["developer_instructions"].strip()
    read_only = name in {"cleanup-worker", "coding-supervisor", "live-validator", "review-worker", "critic"} or name.startswith("reviewer-")
    tools = read_tools if read_only else write_tools
    body = "\n".join([
        "---",
        f"name: {name}",
        f"description: {json.dumps(data['description'])}",
        "subagent: true",
        "model: inherit",
        "commandExecutionPolicy: eager",
        "tools:",
        *(f"  - {tool}" for tool in tools),
        "---",
        "",
        "# Generated by my-codex-config bootstrap.",
        "",
        prompt,
        "",
    ])
    destination = target / name / "agent.md"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(body, encoding="utf-8")
PY
}

retire_agent() {
  local target=$1

  [[ -e "$target" || -L "$target" ]] || return 0
  backup_existing "$target"
}

cleanup() {
  [[ -n "$RENDER_DIR" ]] && rm -rf "$RENDER_DIR"
}
trap cleanup EXIT

main() {
  local rendered name

  [[ -d "$CODEX_SOURCE/agents" ]] || { printf 'Missing Codex agent source: %s\n' "$CODEX_SOURCE/agents" >&2; exit 1; }
  [[ -d "$SKILLS_SOURCE" ]] || { printf 'Missing shared skill source: %s\n' "$SKILLS_SOURCE" >&2; exit 1; }

  python3 - "$HOME/.gemini/antigravity-cli/settings.json" <<'PY'
import json
import pathlib
import tempfile
import sys

path = pathlib.Path(sys.argv[1])
settings = json.loads(path.read_text()) if path.exists() else {}
settings.update(
    toolPermission="always-proceed",
    artifactReviewPolicy="always-proceed",
    enableTerminalSandbox=False,
)
path.parent.mkdir(parents=True, exist_ok=True)
with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False) as output:
    json.dump(settings, output, indent=2)
    output.write("\n")
pathlib.Path(output.name).replace(path)
PY

  ensure_directory "$AGY_CONFIG_ROOT"
  ensure_directory "$AGY_CONFIG_ROOT/plugins"
  ensure_directory "$AGY_PLUGIN_TARGET"
  ensure_directory "$AGY_PLUGIN_TARGET/agents"
  ensure_directory "$AGY_GLOBAL_AGENTS"
  mkdir -p "$HOME/.agents"
  link_managed "$SKILLS_SOURCE" "$HOME/.agents/skills"
  link_managed "$HOME/.agents/skills" "$AGY_CONFIG_ROOT/skills"
  link_managed "$HOME/.agents/skills" "$AGY_PLUGIN_TARGET/skills"

  retire_agent "$AGY_GLOBAL_AGENTS/automation-runner/agent.md"

  RENDER_DIR=$(mktemp -d "${TMPDIR:-/tmp}/my-codex-config-agy.XXXXXX")
  render_agents "$RENDER_DIR"
  for rendered in "$RENDER_DIR"/*/agent.md; do
    name=$(basename "$(dirname "$rendered")")
    ensure_directory "$AGY_PLUGIN_TARGET/agents/$name"
    install_generated_file "$rendered" "$AGY_PLUGIN_TARGET/agents/$name/agent.md"
    ensure_directory "$AGY_GLOBAL_AGENTS/$name"
    link_managed "$AGY_PLUGIN_TARGET/agents/$name/agent.md" "$AGY_GLOBAL_AGENTS/$name/agent.md"
  done

  rendered=$(mktemp "${TMPDIR:-/tmp}/my-codex-config-agy-plugin.XXXXXX")
  printf '{\n  "name": "my-codex-config"\n}\n' > "$rendered"
  install_generated_file "$rendered" "$AGY_PLUGIN_TARGET/plugin.json"
  rm "$rendered"

  printf 'Installed AGY agents and shared skills.\n'
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main
fi
