case "${1:-}" in
  ps)
    [[ -n "${DOCKER_PS_OUTPUT:-}" ]] && printf '%s\n' "$DOCKER_PS_OUTPUT"
    ;;
  info)
    [[ "${DOCKER_MODE:-}" != unavailable ]] || exit 1
    ;;
  inspect)
    if [[ "${2:-}" == --format ]]; then
      if [[ "${3:-}" == *'.Config.Image'* ]]; then
        [[ "${DOCKER_MODE:-}" != identity-fail ]] || exit 1
        printf '%s\n' "${DOCKER_IMAGE:-docker.io/searxng/searxng:latest}"
        exit 0
      fi
      if [[ "${3:-}" == *'.State.Status'* ]]; then
        [[ "${DOCKER_MODE:-}" != inspect-fail ]] || exit 1
        count=0
        if [[ -n "${DOCKER_INSPECT_COUNT_FILE:-}" && -e "$DOCKER_INSPECT_COUNT_FILE" ]]; then
          count=$(<"$DOCKER_INSPECT_COUNT_FILE")
        fi
        ((count += 1))
        case "${DOCKER_STARTUP_SCENARIO:-stable}" in
          immediate-exit) printf 'exited false false 0\n' ;;
          restart)
            if ((count >= 2)); then
              printf 'running true false 1\n'
            else
              printf 'running true false 0\n'
            fi
            ;;
          *) printf 'running true false 0\n' ;;
        esac
        [[ -z "${DOCKER_INSPECT_COUNT_FILE:-}" ]] || printf '%s\n' "$count" > "$DOCKER_INSPECT_COUNT_FILE"
        exit 0
      fi
    fi
    [[ -n "${DOCKER_STATE:-}" && -e "$DOCKER_STATE" ]]
    ;;
  start)
    [[ -z "${DOCKER_STATE:-}" ]] || : > "$DOCKER_STATE"
    [[ -z "${DOCKER_INSPECT_COUNT_FILE:-}" ]] || : > "$DOCKER_INSPECT_COUNT_FILE"
    ;;
  run)
    if [[ "${DOCKER_MODE:-}" == run-fail ]]; then
      exit 1
    fi
    [[ -z "${DOCKER_STATE:-}" ]] || : > "$DOCKER_STATE"
    [[ -z "${DOCKER_INSPECT_COUNT_FILE:-}" ]] || : > "$DOCKER_INSPECT_COUNT_FILE"
    ;;
esac
EOF
