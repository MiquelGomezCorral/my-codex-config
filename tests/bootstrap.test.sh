run_startup_case() {
  local name=$1
  local scenario=$2
  local mode=$3
  local existing=$4
  local image=${5:-docker.io/searxng/searxng:latest}
  local home="$TEST_HOME/$name-home"
  local state="$TEST_HOME/$name.state"
  local inspect_count="$TEST_HOME/$name.inspect-count"

  mkdir -p "$home"
  if [[ "$existing" == true ]]; then
    : > "$state"
  fi
  DOCKER_MODE="$mode" DOCKER_STARTUP_SCENARIO="$scenario" \
    DOCKER_IMAGE="$image" \
    PATH="$STUB_BIN:/usr/bin:/bin" STUB_LOG="$STUB_LOG" PI_LOG="$PI_LOG" \
    DOCKER_STATE="$state" DOCKER_INSPECT_COUNT_FILE="$inspect_count" HOME="$home" \
    "$REPO_ROOT/bootstrap.sh" --home "$home" --pi \
    > "$TEST_HOME/$name.out" 2> "$TEST_HOME/$name.err"
  assert_pi_connector "$home"
}

