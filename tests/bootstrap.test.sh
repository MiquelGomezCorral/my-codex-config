#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
TEST_HOME=$(mktemp -d)
trap 'rm -rf "$TEST_HOME"' EXIT

set -- --home "$TEST_HOME/home"
source "$REPO_ROOT/bootstrap.sh"

mkdir -p "$CODEX_TARGET"
printf 'keep this runtime state\n' > "$CODEX_TARGET/auth.json"
printf 'old config\n' > "$CODEX_TARGET/config.toml"

install_config

[[ -f "$CODEX_TARGET/config.toml" ]]
[[ ! -L "$CODEX_TARGET/config.toml" ]]
cmp -s "$CODEX_TARGET/config.toml" "$CODEX_SOURCE/config.toml"
[[ -L "$CODEX_TARGET/hooks.json" ]]
[[ -L "$CODEX_TARGET/rules/my-opencode-config.rules" ]]
for name in coder cleanup-worker commit-worker automation-runner review-worker reviewer-quick reviewer-reasoning reviewer-arch reviewer-e2e; do
  [[ -f "$CODEX_TARGET/agents/$name.toml" ]]
  [[ ! -L "$CODEX_TARGET/agents/$name.toml" ]]
  cmp -s "$CODEX_TARGET/agents/$name.toml" "$CODEX_SOURCE/agents/$name.toml"
done
[[ -L "$CODEX_TARGET/bin/ponytail-hook.mjs" ]]
[[ -L "$CODEX_TARGET/vault-context" ]]
[[ -L "$TEST_HOME/home/.agents/skills" ]]
[[ ! -e "$CODEX_TARGET/bin/opencode-go-worker.mjs" ]]
[[ ! -e "$CODEX_TARGET/agents/opencode-go-runner.toml" ]]

grep -q '^# Generated by my-codex-config bootstrap\.' "$CODEX_TARGET/AGENTS.md"
grep -q '^# Security Rules$' "$CODEX_TARGET/AGENTS.md"
[[ "$(<"$CODEX_TARGET/auth.json")" == 'keep this runtime state' ]]
[[ -e "$BACKUP_ROOT/.codex/config.toml" ]]
[[ ! -e "$REPO_ROOT/config/skills" ]]
HOME="$TEST_HOME/home" CODEX_HOME="$CODEX_TARGET" codex mcp-server --strict-config < /dev/null >/dev/null

printf '\n[hooks.state]\n' >> "$CODEX_TARGET/config.toml"
! grep -q '\[hooks.state\]' "$CODEX_SOURCE/config.toml"
install_config
[[ -f "$CODEX_TARGET/config.toml" ]]
[[ ! -L "$CODEX_TARGET/config.toml" ]]
cmp -s "$CODEX_TARGET/config.toml" "$CODEX_SOURCE/config.toml"
[[ -e "$CODEX_TARGET/auth.json" ]]
