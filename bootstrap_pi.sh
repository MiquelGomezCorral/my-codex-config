#!/usr/bin/env bash
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
CODEX_SOURCE="$ROOT/codex"
SKILLS_SOURCE="$ROOT/agent-home/skills"
PI_AGENT_ROOT="${PI_CODING_AGENT_DIR:-$HOME/.pi/agent}"
BACKUP_ROOT="${BACKUP_ROOT:-${XDG_STATE_HOME:-$HOME/.local/state}/my-codex-config/backups/$(date +%Y%m%d-%H%M%S)}"
INSTALL_EXTENSION=false
SEARXNG_MCP_ENABLED=true
RENDER_DIR=""

source "$ROOT/config/bin/codegraph-dependency.sh"

usage() {
  printf 'Usage: %s [--install-extension] [--no-searxng-mcp]\n' "$0"
}

while (($#)); do
  case "$1" in
    --install-extension) INSTALL_EXTENSION=true ;;
    --no-searxng-mcp) SEARXNG_MCP_ENABLED=false ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
  esac
  shift
done

backup_existing() {
  local target=$1
  local relative_target backup_target backup_index=1

  relative_target=${target#"$HOME"/}
  [[ "$relative_target" != "$target" ]] || relative_target=".pi/agent/${target##*/}"
  backup_target="$BACKUP_ROOT/$relative_target"
  while [[ -e "$backup_target" || -L "$backup_target" ]]; do
    backup_target="$BACKUP_ROOT/$relative_target.$backup_index"
    ((backup_index += 1))
  done
  mkdir -p -m 700 "$(dirname "$backup_target")"
  chmod 700 "$BACKUP_ROOT"
  mv "$target" "$backup_target"
  printf 'Backed up %s to %s\n' "$target" "$backup_target"
}

ensure_directory() {
  local target=$1

  if [[ -e "$target" || -L "$target" ]] && [[ ! -d "$target" || -L "$target" ]]; then
    backup_existing "$target"
  fi
  mkdir -p "$target"
}

link_managed() {
  local source=$1
  local target=$2

  mkdir -p "$(dirname "$target")"
  if [[ -L "$target" && "$(readlink "$target")" == "$source" ]]; then
    return
  fi
  if [[ -e "$target" || -L "$target" ]]; then
    backup_existing "$target"
  fi
  ln -s "$source" "$target"
}

install_generated_file() {
  local source=$1
  local target=$2

  if [[ -e "$target" || -L "$target" ]] && {
    [[ -L "$target" ]] || ! grep -q '^# Generated by my-codex-config bootstrap\.$' "$target" 2>/dev/null
  }; then
    backup_existing "$target"
  fi
  install -m 600 "$source" "$target"
}

render_agents() {
  local target=$1

  python3 - "$CODEX_SOURCE/agents" "$target" <<'PY'
import json
import pathlib
import sys
import tomllib

source = pathlib.Path(sys.argv[1])
target = pathlib.Path(sys.argv[2])
skills = {
    "cleanup-worker": ["cleanup", "code-quality", "super-agent", "test-audit", "writing"],
    "coder": ["code", "code-quality", "super-agent", "test-audit", "writing"],
    "git-worker": ["git", "writing"],
    "coding-supervisor": ["code-quality", "review", "review-findings", "super-agent", "test-audit", "workflow", "writing"],
    "live-validator": ["code-quality", "computer-use", "review", "test-audit", "workflow", "writing"],
    "critic": ["decision-records", "web-search", "writing"],
    "review-worker": ["code-quality", "review", "review-findings", "super-agent", "test-audit", "writing"],
    "reviewer-arch": ["code-quality", "review", "test-audit", "writing"],
    "reviewer-e2e": ["code-quality", "review", "test-audit", "writing"],
    "reviewer-quick": ["code-quality", "review", "test-audit", "writing"],
    "reviewer-reasoning": ["code-quality", "review", "test-audit", "writing"],
}

for path in sorted(source.glob("*.toml")):
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    name = data["name"]
    if name != path.stem:
        raise SystemExit(f"Agent name does not match filename: {path}")
    prompt = data["developer_instructions"].strip()
    read_only = name in {"cleanup-worker", "coding-supervisor", "live-validator", "review-worker", "critic"} or name.startswith("reviewer-")
    tools = ["read", "grep", "find", "ls", "bash"]
    if not read_only:
        tools += ["edit", "write"]
    thinking = data.get("model_reasoning_effort", "")
    if thinking not in {"minimal", "low", "medium", "high", "xhigh", "max"}:
        thinking = "high"
    body = "\n".join([
        "---",
        f"name: {name}",
        f"description: {json.dumps(data['description'])}",
        f"tools: {', '.join(tools)}",
        f"thinking: {thinking}",
        "systemPromptMode: replace",
        "inheritProjectContext: true",
        "inheritSkills: false",
        f"skills: {', '.join(skills.get(name, ['writing']))}",
        *(["allowNestedSubagents: true"] if name in {"cleanup-worker", "coding-supervisor", "review-worker"} else []),
        "defaultProgress: true",
        "---",
        "",
        "# Generated by my-codex-config bootstrap.",
        "",
        prompt,
        "",
    ])
    (target / f"{name}.md").write_text(body, encoding="utf-8")
PY
}

retire_agent() {
  local target=$1

  [[ -e "$target" || -L "$target" ]] || return 0
  backup_existing "$target"
}

install_mcp_config() {
  local target="$PI_AGENT_ROOT/mcp.json"
  local temporary

  temporary=$(mktemp "$PI_AGENT_ROOT/mcp.json.XXXXXX")
  python3 - "$target" "$temporary" "$SEARXNG_MCP_ENABLED" <<'PY'
import json
import pathlib
import sys

target = pathlib.Path(sys.argv[1])
temporary = pathlib.Path(sys.argv[2])
searxng_enabled = sys.argv[3] == "true"

data = json.loads(target.read_text(encoding="utf-8")) if target.exists() else {}
if not isinstance(data, dict):
    raise SystemExit(f"Pi MCP config must be an object: {target}")
servers = data.setdefault("mcpServers", {})
if not isinstance(servers, dict):
    raise SystemExit(f"Pi MCP config mcpServers must be an object: {target}")

servers["codegraph"] = {
    "command": "codegraph",
    "args": ["serve", "--mcp"],
    "lifecycle": "lazy",
    "directTools": True,
}
if searxng_enabled:
    servers["searxng"] = {
        "command": "mcp-searxng",
        "env": {"SEARXNG_URL": "http://localhost:8080"},
        "lifecycle": "lazy",
        "directTools": True,
    }
elif servers.get("searxng") == {
    "command": "mcp-searxng",
    "env": {"SEARXNG_URL": "http://localhost:8080"},
    "lifecycle": "lazy",
    "directTools": True,
}:
    del servers["searxng"]

temporary.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
PY
  if [[ -f "$target" ]] && cmp -s "$temporary" "$target"; then
    rm "$temporary"
    return
  fi
  if [[ -e "$target" || -L "$target" ]]; then
    backup_existing "$target"
  fi
  install -m 600 "$temporary" "$target"
  rm "$temporary"
}

install_pi_extensions() {
  pi install npm:pi-subagents
  pi install npm:pi-mcp-adapter@2.34.0
  if $SEARXNG_MCP_ENABLED; then
    pi install npm:mcp-searxng@1.11.1
  fi
}

main() {
  local name

  [[ -d "$CODEX_SOURCE/agents" ]] || { printf 'Missing Codex agent source: %s\n' "$CODEX_SOURCE/agents" >&2; exit 1; }
  [[ -d "$SKILLS_SOURCE" ]] || { printf 'Missing shared skill source: %s\n' "$SKILLS_SOURCE" >&2; exit 1; }

  ensure_directory "$PI_AGENT_ROOT"
  ensure_directory "$PI_AGENT_ROOT/agents"
  mkdir -p "$HOME/.agents"
  link_managed "$SKILLS_SOURCE" "$HOME/.agents/skills"
  link_managed "$HOME/.agents/skills" "$PI_AGENT_ROOT/skills"
  retire_agent "$PI_AGENT_ROOT/agents/automation-runner.md"

  RENDER_DIR=$(mktemp -d "${TMPDIR:-/tmp}/my-codex-config-pi.XXXXXX")
  render_agents "$RENDER_DIR"
  for name in "$RENDER_DIR"/*.md; do
    install_generated_file "$name" "$PI_AGENT_ROOT/agents/$(basename "$name")"
  done

  ensure_codegraph
  install_mcp_config
  if $INSTALL_EXTENSION; then
    install_pi_extensions
  fi
  printf 'Installed Pi agents and shared skills.\n'
}

cleanup() {
  [[ -n "$RENDER_DIR" ]] && rm -rf "$RENDER_DIR"
}
trap cleanup EXIT

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main
fi
