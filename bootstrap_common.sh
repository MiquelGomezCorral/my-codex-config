#!/usr/bin/env bash
set -euo pipefail

COMMON_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
COMMON_DATA_ROOT="${XDG_DATA_HOME:-$HOME/.local/share}/my-codex-config"
COMMON_STATE_ROOT="${XDG_STATE_HOME:-$HOME/.local/state}/my-codex-config"
COMMON_BACKUP_ROOT="${BACKUP_ROOT:-$COMMON_STATE_ROOT/backups/$(date +%Y%m%d-%H%M%S)}"
COMMON_SEARXNG_DATA_ROOT="$COMMON_DATA_ROOT/searxng"
COMMON_SEARXNG_CONTAINER="${SEARXNG_CONTAINER:-my-codex-config-searxng}"
COMMON_SEARXNG_IMAGE="${SEARXNG_IMAGE:-docker.io/searxng/searxng:latest}"
COMMON_PORTABLE_ROOT="$COMMON_DATA_ROOT/external-skills"
COMMON_CURRENT_SKILL_ROOTS=()

common_die() {
  printf '%s\n' "$1" >&2
  exit 1
}

common_backup_existing() {
  local target=$1 relative_target backup_target backup_index=1

  relative_target=${target#"$HOME"/}
  [[ "$relative_target" != "$target" ]] || relative_target="${target#/}"
  backup_target="$COMMON_BACKUP_ROOT/$relative_target"
  while [[ -e "$backup_target" || -L "$backup_target" ]]; do
    backup_target="$COMMON_BACKUP_ROOT/$relative_target.$backup_index"
    ((backup_index += 1))
  done
  mkdir -p -m 700 "$(dirname "$backup_target")"
  chmod 700 "$COMMON_BACKUP_ROOT"
  mv "$target" "$backup_target"
  printf 'Backed up %s to %s\n' "$target" "$backup_target"
}

common_ensure_directory() {
  local target=$1

  if [[ -e "$target" || -L "$target" ]] && [[ ! -d "$target" || -L "$target" ]]; then
    if [[ -L "$target" && -d "$target" ]]; then
      return 0
    fi
    common_backup_existing "$target"
  fi
  mkdir -p "$target"
}

common_link_managed() {
  local source=$1 target=$2

  mkdir -p "$(dirname "$target")"
  if [[ -L "$target" && "$(readlink "$target")" == "$source" ]]; then
    return 0
  fi
  if [[ -e "$target" || -L "$target" ]]; then
    common_backup_existing "$target"
  fi
  ln -s "$source" "$target"
}

common_install_generated_file() {
  local source=$1 target=$2

  if [[ -f "$target" && ! -L "$target" ]] && cmp -s "$source" "$target"; then
    chmod 600 "$target"
    return 0
  fi
  if [[ -e "$target" || -L "$target" ]] && {
    [[ -L "$target" ]] || ! grep -Eq '^# Generated by my-(codex|harness)-config bootstrap\.' "$target" 2>/dev/null
  }; then
    common_backup_existing "$target"
  fi
  install -m 600 "$source" "$target"
}

common_install_codegraph() {
  source "$COMMON_ROOT/config/bin/codegraph-dependency.sh"
  ensure_codegraph
}

common_link_ocr() {
  common_link_managed "$COMMON_ROOT/config/skills/review/scripts/ocr-opencode-go" "$HOME/.local/bin/ocr-go"
}

common_install_btca() {
  if command -v btca >/dev/null 2>&1; then
    return 0
  fi
  command -v bun >/dev/null 2>&1 || common_die 'BTCA is missing and requires Bun. Install Bun, then rerun this bootstrap.'
  printf 'Installing BTCA...\n'
  bun add -g btca
  command -v btca >/dev/null 2>&1 || common_die 'BTCA installation completed but btca is not on PATH.'
}

common_install_lintapple() {
  if command -v lintapple >/dev/null 2>&1; then
    return 0
  fi
  command -v npm >/dev/null 2>&1 || common_die 'Missing npm; cannot install lintapple.'
  printf 'Installing lintapple (lintapple@0.1.20)...\n'
  npm install --global lintapple@0.1.20
  command -v lintapple >/dev/null 2>&1 || common_die 'lintapple installation completed but lintapple is not on PATH.'
}

common_has_pinned_searxng_connector() {
  local path_entry connector
  local -a path_entries=()
  IFS=: read -r -a path_entries <<< "${PATH:-}"
  for path_entry in "${path_entries[@]}"; do
    connector="${path_entry:-.}/mcp-searxng"
    [[ -f "$connector" && -x "$connector" ]] || continue
    if python3 - "$connector" "${PI_CODING_AGENT_DIR:-$HOME/.pi/agent}" <<'PY'
import json
import pathlib
import sys

binary = pathlib.Path(sys.argv[1]).resolve()
pi_root = pathlib.Path(sys.argv[2]).expanduser().resolve()
if binary == pi_root or pi_root in binary.parents:
    raise SystemExit(1)
for directory in binary.parents:
    package = directory / "package.json"
    if not package.is_file():
        continue
    try:
        data = json.loads(package.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        continue
    if data.get("name") == "mcp-searxng" and data.get("version") == "1.11.1":
        raise SystemExit(0)
    raise SystemExit(1)
raise SystemExit(1)
PY
    then
      return 0
    fi
  done
  return 1
}

common_install_searxng_connector() {
  if common_has_pinned_searxng_connector; then
    return 0
  fi
  command -v npm >/dev/null 2>&1 || common_die 'Missing npm; cannot install the SearXNG MCP connector.'
  printf 'Installing the shared SearXNG MCP connector (mcp-searxng@1.11.1)...\n'
  npm install --global mcp-searxng@1.11.1
  common_has_pinned_searxng_connector || common_die 'SearXNG connector installation completed without a shared pinned executable on PATH.'
}

common_clone_portable() {
  local name=$1 repository=$2 required=$3 destination temporary root source portable_name skip
  local -a roots=() names=()
  destination="$COMMON_PORTABLE_ROOT/$name"

  if [[ -f "$destination/$required/SKILL.md" ]]; then
    return 0
  fi
  if [[ -e "$destination" || -L "$destination" ]]; then
    common_backup_existing "$destination"
  fi

  roots=("$HOME/.agents/skills" "$HOME/.codex/skills" "$HOME/.claude/skills")
  roots+=("${PI_CODING_AGENT_DIR:-$HOME/.pi/agent}/skills")
  roots+=("${CLAUDE_CONFIG_DIR:-$HOME/.claude}/skills")
  roots+=("${AGY_CLI_ROOT:-$HOME/.gemini/antigravity-cli}/skills")
  roots+=("${AGY_CONFIG_ROOT:-$HOME/.gemini/config}/plugins/my-codex-config/skills")
  names=("$name")
  if [[ "$name" == excalidraw ]]; then
    names+=(skill)
  fi
  for root in "${roots[@]}"; do
    skip=false
    for source in "${COMMON_CURRENT_SKILL_ROOTS[@]}"; do
      if [[ "$root" == "$source" ]]; then
        skip=true
        break
      fi
    done
    if [[ "$skip" == true ]]; then
      continue
    fi
    for portable_name in "${names[@]}"; do
      source="$root/$portable_name"
      [[ -f "$source/SKILL.md" ]] || continue
      mkdir -p "$(dirname "$destination/$required")"
      ln -s "$source" "$destination/$required"
      return 0
    done
  done

  command -v git >/dev/null 2>&1 || common_die "Missing git; cannot acquire portable $name skill."
  mkdir -p "$COMMON_PORTABLE_ROOT"
  temporary=$(mktemp -d "$COMMON_PORTABLE_ROOT/.${name}.XXXXXX")
  if ! git clone --depth 1 "$repository" "$temporary/source"; then
    rm -rf "$temporary"
    common_die "Could not acquire portable $name skill from $repository."
  fi
  [[ -f "$temporary/source/$required/SKILL.md" ]] || {
    rm -rf "$temporary"
    common_die "Portable skill source does not contain $required/SKILL.md: $repository"
  }
  mv "$temporary/source" "$destination"
  rmdir "$temporary"
}

common_prepare_portable_skills() {
  common_clone_portable diagram-design https://github.com/cathrynlavery/diagram-design.git skills/diagram-design
  common_clone_portable excalidraw https://github.com/fabricioartur/codex-excalidraw-skill.git skill
}

common_searxng_image_matches() {
  case "$1" in
    "$COMMON_SEARXNG_IMAGE"|searxng/searxng|searxng/searxng:*|searxng/searxng@*|docker.io/searxng/searxng|docker.io/searxng/searxng:*|docker.io/searxng/searxng@*) return 0 ;;
  esac
  return 1
}

common_warn() {
  printf 'Warning: %s\n' "$1" >&2
}

common_check_searxng_startup() {
  local container=$1 sample status running restarting restart_count initial_restart_count

  if ! sample=$(docker inspect --format '{{.State.Status}} {{.State.Running}} {{.State.Restarting}} {{.RestartCount}}' "$container" 2>/dev/null); then
    common_warn "Could not inspect SearXNG container $container during startup check."
    return 1
  fi
  read -r status running restarting restart_count <<< "$sample"
  if [[ "$status" != running || "$running" != true || "$restarting" == true || ! "$restart_count" =~ ^[0-9]+$ ]]; then
    common_warn "SearXNG container $container is not running during startup check."
    return 1
  fi
  initial_restart_count=$restart_count

  for _ in 1 2 3 4 5; do
    sleep 1
    if ! sample=$(docker inspect --format '{{.State.Status}} {{.State.Running}} {{.State.Restarting}} {{.RestartCount}}' "$container" 2>/dev/null); then
      common_warn "Could not inspect SearXNG container $container during startup check."
      return 1
    fi
    read -r status running restarting restart_count <<< "$sample"
    if [[ "$status" != running || "$running" != true || "$restarting" == true || ! "$restart_count" =~ ^[0-9]+$ || "$restart_count" != "$initial_restart_count" ]]; then
      common_warn "SearXNG container $container restarted or stopped during startup check."
      return 1
    fi
  done
}

# Writes the per-machine settings: the repository file plus a random secret key, which the
# image refuses to start without. The secret never enters the repository.
common_write_searxng_settings() {
  local target=$1 secret

  secret=$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')
  (
    umask 077
    {
      cat "$COMMON_ROOT/config/searxng/settings.yml"
      printf 'server:\n  secret_key: "%s"\n' "$secret"
    } > "$target"
  )
}

common_install_searxng() {
  local existing existing_image data_root config_root cache_root

  if ! command -v docker >/dev/null 2>&1; then
    common_warn 'Docker is not installed; skipping SearXNG deployment.'
    return 0
  fi
  existing=$(docker ps --format '{{.Names}} {{.Ports}}' 2>/dev/null | awk '/127\.0\.0\.1:8080->|0\.0\.0\.0:8080->|\[::\]:8080->/ {print $1; exit}') || true
  if [[ -n "$existing" ]]; then
    if ! existing_image=$(docker inspect --format '{{.Config.Image}}' "$existing" 2>/dev/null); then
      common_warn "Port 8080 is occupied by $existing, but its image could not be inspected; skipping SearXNG deployment."
      return 0
    fi
    if ! common_searxng_image_matches "$existing_image"; then
      common_warn "Port 8080 is occupied by $existing ($existing_image), not SearXNG; skipping deployment."
      return 0
    fi
    printf 'Reusing running SearXNG container %s on http://localhost:8080.\n' "$existing"
    return 0
  fi
  if ! docker info >/dev/null 2>&1; then
    common_warn 'Docker is unavailable; skipping SearXNG deployment.'
    return 0
  fi

  if docker inspect "$COMMON_SEARXNG_CONTAINER" >/dev/null 2>&1; then
    if ! existing_image=$(docker inspect --format '{{.Config.Image}}' "$COMMON_SEARXNG_CONTAINER" 2>/dev/null); then
      common_warn "Managed container $COMMON_SEARXNG_CONTAINER image could not be inspected; skipping restart."
      return 0
    fi
    if ! common_searxng_image_matches "$existing_image"; then
      common_warn "Managed container $COMMON_SEARXNG_CONTAINER ($existing_image) is not SearXNG; skipping restart."
      return 0
    fi
    if docker start "$COMMON_SEARXNG_CONTAINER" >/dev/null 2>&1 && common_check_searxng_startup "$COMMON_SEARXNG_CONTAINER"; then
      printf 'Started managed SearXNG container %s.\n' "$COMMON_SEARXNG_CONTAINER"
    else
      common_warn "Unable to start managed SearXNG container $COMMON_SEARXNG_CONTAINER."
    fi
    return 0
  fi

  data_root="$COMMON_SEARXNG_DATA_ROOT"
  config_root="$data_root/config"
  cache_root="$data_root/cache"
  mkdir -p "$config_root" "$cache_root"
  if [[ ! -e "$config_root/settings.yml" ]]; then
    common_write_searxng_settings "$config_root/settings.yml"
  fi
  if ! docker run --detach --name "$COMMON_SEARXNG_CONTAINER" --restart unless-stopped \
    --publish 127.0.0.1:8080:8080 \
    --volume "$config_root:/etc/searxng" \
    --volume "$cache_root:/var/cache/searxng" \
    "$COMMON_SEARXNG_IMAGE" >/dev/null; then
    common_warn 'Unable to start SearXNG on 127.0.0.1:8080; check Docker and port availability. Continuing with the remaining setup.'
  elif common_check_searxng_startup "$COMMON_SEARXNG_CONTAINER"; then
    printf 'Started SearXNG container %s.\n' "$COMMON_SEARXNG_CONTAINER"
  fi
}

common_install_shared() {
  local searxng_enabled=true searxng_mcp_enabled=true arg

  while (($#)); do
    arg=$1
    case "$arg" in
      --no-searxng) searxng_enabled=false ;;
      --no-searxng-mcp) searxng_mcp_enabled=false ;;
      *) common_die "Unknown common installer option: $arg" ;;
    esac
    shift
  done

  common_install_codegraph
  common_install_btca
  common_install_lintapple
  if $searxng_mcp_enabled; then
    common_install_searxng_connector
  fi
  common_prepare_portable_skills
  common_link_ocr
  common_link_managed "$COMMON_ROOT/config/bin/explore.py" "$HOME/.local/bin/explore"
  if $searxng_enabled; then
    common_install_searxng
  fi
}
